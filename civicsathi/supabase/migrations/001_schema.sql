-- CivicSathi - 001: tables, constraints, indexes
-- Run migrations 001 -> 005 in order (Supabase Dashboard -> SQL Editor, or `supabase db push`).

-- ---------------------------------------------------------------------------
-- profiles: one row per authenticated user (created by a trigger, see 002)
-- ---------------------------------------------------------------------------
create table if not exists public.profiles (
  id           uuid primary key references auth.users (id) on delete cascade,
  full_name    text not null default '' check (char_length(full_name) <= 100),
  email        text not null,
  role         text not null default 'citizen' check (role in ('citizen', 'admin')),
  phone_number text check (phone_number is null or phone_number ~ '^[0-9+() -]{7,20}$'),
  created_at   timestamptz not null default now()
);

create index if not exists profiles_role_idx on public.profiles (role);

-- ---------------------------------------------------------------------------
-- complaints
-- ---------------------------------------------------------------------------
create sequence if not exists public.complaint_number_seq start 1;

create table if not exists public.complaints (
  id               uuid primary key default gen_random_uuid(),
  -- Readable reference such as CS-2026-000042. Always generated by trigger (see 002).
  complaint_number text not null unique,
  user_id          uuid not null default auth.uid() references public.profiles (id) on delete cascade,
  title            text not null check (char_length(title) between 5 and 120),
  description      text not null check (char_length(description) between 20 and 1000),
  category         text not null check (category in (
                     'roads', 'garbage', 'streetlights', 'water_leakage',
                     'drainage', 'public_property', 'other')),
  -- Despite the name (kept from the project spec) this stores the STORAGE PATH of the photo
  -- inside the private "complaint-images" bucket, e.g. "<user_id>/<uuid>.jpg".
  -- The app turns it into a short-lived signed URL when displaying it.
  image_url        text,
  state            text not null check (char_length(state) between 2 and 60),
  city             text not null check (char_length(city) between 2 and 80),
  locality         text not null check (char_length(locality) between 3 and 120),
  latitude         double precision check (latitude  is null or latitude  between -90  and 90),
  longitude        double precision check (longitude is null or longitude between -180 and 180),
  status           text not null default 'pending'
                     check (status in ('pending', 'in_progress', 'resolved', 'rejected')),
  admin_remarks    text check (admin_remarks is null or char_length(admin_remarks) <= 1000),
  created_at       timestamptz not null default now(),
  updated_at       timestamptz not null default now(),
  -- coordinates are either both present or both absent
  constraint complaints_coords_pair check ((latitude is null) = (longitude is null))
);

create index if not exists complaints_user_idx       on public.complaints (user_id, created_at desc);
create index if not exists complaints_status_idx     on public.complaints (status);
create index if not exists complaints_category_idx   on public.complaints (category);
create index if not exists complaints_created_at_idx on public.complaints (created_at desc);

-- ---------------------------------------------------------------------------
-- complaint_history: every status change (and the initial submission)
-- ---------------------------------------------------------------------------
create table if not exists public.complaint_history (
  id           uuid primary key default gen_random_uuid(),
  complaint_id uuid not null references public.complaints (id) on delete cascade,
  old_status   text check (old_status is null or old_status in ('pending', 'in_progress', 'resolved', 'rejected')),
  new_status   text not null check (new_status in ('pending', 'in_progress', 'resolved', 'rejected')),
  remarks      text check (remarks is null or char_length(remarks) <= 1000),
  updated_by   uuid references public.profiles (id) on delete set null,
  created_at   timestamptz not null default now()
);

create index if not exists complaint_history_complaint_idx
  on public.complaint_history (complaint_id, created_at);

-- ---------------------------------------------------------------------------
-- notifications (in-app)
-- ---------------------------------------------------------------------------
create table if not exists public.notifications (
  id           uuid primary key default gen_random_uuid(),
  user_id      uuid not null references public.profiles (id) on delete cascade,
  complaint_id uuid references public.complaints (id) on delete cascade,
  -- `type` lets the UI show the message in the user's language (English / Hindi).
  type         text not null default 'info'
                 check (type in ('submitted', 'pending', 'in_progress', 'resolved', 'rejected', 'info')),
  title        text not null,
  message      text not null,
  is_read      boolean not null default false,
  created_at   timestamptz not null default now()
);

create index if not exists notifications_user_idx
  on public.notifications (user_id, is_read, created_at desc);
